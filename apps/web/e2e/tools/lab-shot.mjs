import { chromium } from "@playwright/test";
const S = process.argv[2];
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium", args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:3100/search", { waitUntil: "networkidle" });
await page.fill("#q", "How do tariffs affect gross margin?");
await page.getByRole("button", { name: "Expand" }).click();
await page.getByRole("group", { name: "Neighbour expansion" }).getByRole("button", { name: "1" }).click();
await page.getByRole("group", { name: "Token budget" }).getByRole("button", { name: "2K" }).click();
await page.getByRole("button", { name: "Search", exact: true }).click();
await page.waitForSelector('[data-testid="hit"]');
await page.waitForTimeout(700);
await page.screenshot({ path: `${S}/lab-units.png`, fullPage: false });
await page.getByRole("tab", { name: /Context/ }).click();
await page.waitForSelector('[data-testid="budget-bar"]');
await page.waitForTimeout(400);
await page.screenshot({ path: `${S}/lab-context.png`, fullPage: false });
console.log("hits:", await page.locator('[data-testid="hit"]').count(), "| url:", page.url().slice(0, 120), "| errors:", errors.length ? errors.join(" || ") : "none");
await browser.close();
